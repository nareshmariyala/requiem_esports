
-- 1. Member profiles
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  gamer_tag text not null default 'New Player',
  preferred_game text,
  membership_status text not null default 'pending'
    check (membership_status in ('pending', 'approved', 'rejected')),
  created_at timestamptz not null default now()
);

-- 2. Games
create table if not exists public.games (
  id bigint generated by default as identity primary key,
  name text not null unique,
  genre text,
  is_active boolean not null default true
);

-- 3. Squads
create table if not exists public.squads (
  id bigint generated by default as identity primary key,
  name text not null unique,
  game_id bigint references public.games(id) on delete set null,
  description text
);

-- 4. Match results
create table if not exists public.match_results (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles(id) on delete cascade,
  points integer not null default 0 check (points >= 0),
  won boolean not null default false,
  verified boolean not null default false,
  created_at timestamptz not null default now()
);

-- 5. Automatically create a pending profile at signup
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles
    (id, gamer_tag, preferred_game, membership_status)
  values (
    new.id,
    coalesce(
      nullif(new.raw_user_meta_data ->> 'gamer_tag', ''),
      'New Player'
    ),
    nullif(new.raw_user_meta_data ->> 'preferred_game', ''),
    'pending'
  )
  on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;

create trigger on_auth_user_created
after insert on auth.users
for each row
execute procedure public.handle_new_user();

-- 6. Enable row-level security
alter table public.profiles enable row level security;
alter table public.games enable row level security;
alter table public.squads enable row level security;
alter table public.match_results enable row level security;

-- Members can read only their own profile
drop policy if exists "read own profile" on public.profiles;

create policy "read own profile"
on public.profiles
for select to authenticated
using (auth.uid() = id);

-- Public can read active games
drop policy if exists "public read active games" on public.games;

create policy "public read active games"
on public.games
for select to anon, authenticated
using (is_active = true);

-- Public can read squad details
drop policy if exists "public read squads" on public.squads;

create policy "public read squads"
on public.squads
for select to anon, authenticated
using (true);

-- Only verified results can be read directly
drop policy if exists "public read verified match results"
on public.match_results;

create policy "public read verified match results"
on public.match_results
for select to anon, authenticated
using (verified = true);

-- 7. Public leaderboard with aggregate scores
create or replace view public.leaderboard_public as
select
  p.gamer_tag,
  sum(m.points)::bigint as points,
  count(*) filter (where m.won = true)::bigint as wins,
  null::text as squad
from public.profiles p
join public.match_results m
  on m.profile_id = p.id
where p.membership_status = 'approved'
  and m.verified = true
group by p.id, p.gamer_tag;

grant select on public.leaderboard_public to anon, authenticated;

